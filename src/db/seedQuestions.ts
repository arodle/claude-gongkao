export function buildSeedQuestions(nodeMap: Map<string, string>): Question[] {
  const now = Date.now()
  return SEED_QUESTIONS_RAW.map((q) => ({
    id: `q-builtin-${crypto.randomUUID().slice(0, 8)}`,
    user_id: CURRENT_USER_ID,
    stem: q.stem,
    options: q.options,
    correct_answer: q.correct,
    source_node_ids: q.nodes.map((n) => nodeMap.get(n) ?? ''),
    question_type: 'single_choice' as const,
    source: 'builtin' as const,
    updated_at: now,
  }))
}
